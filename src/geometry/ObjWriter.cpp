#include "geometry/ObjWriter.h"

#include <fstream>
#include <stdexcept>

namespace space {

namespace {

namespace fs = std::filesystem;

std::string texturePath(const fs::path& texture, const fs::path& outDir, bool copy)
{
    if (copy) {
        const fs::path dest = outDir / "textures" / texture.filename();
        fs::create_directories(dest.parent_path());
        fs::copy_file(texture, dest, fs::copy_options::overwrite_existing);
        return "textures/" + texture.filename().generic_string();
    }
    std::error_code ec;
    fs::path rel = fs::relative(texture, outDir, ec);
    return (ec || rel.empty() ? texture : rel).generic_string();
}

void writeVec3(std::ofstream& out, const char* key, const glm::vec3& v)
{
    out << key << ' ' << v.x << ' ' << v.y << ' ' << v.z << '\n';
}

} // namespace

void writeObj(const ModelData& model, const fs::path& objPath, const ObjWriteOptions& options)
{
    const fs::path outDir = fs::absolute(objPath).parent_path();
    fs::path mtlPath = objPath;
    mtlPath.replace_extension(".mtl");

    std::ofstream mtl(mtlPath);
    if (!mtl)
        throw std::runtime_error("Cannot write " + mtlPath.string());
    for (const MaterialDesc& m : model.materials) {
        mtl << "newmtl " << m.name << '\n';
        writeVec3(mtl, "Ka", m.ambient);
        writeVec3(mtl, "Kd", m.diffuse);
        writeVec3(mtl, "Ks", m.specular);
        writeVec3(mtl, "Ke", m.emissive);
        mtl << "Ns " << m.shininess << "\nd " << m.opacity << "\nillum 2\n";
        if (!m.diffuseMap.empty())
            mtl << "map_Kd " << texturePath(m.diffuseMap, outDir, options.copyTextures) << '\n';
        if (!m.emissiveMap.empty())
            mtl << "map_Ke " << texturePath(m.emissiveMap, outDir, options.copyTextures) << '\n';
        mtl << '\n';
    }

    std::ofstream obj(objPath);
    if (!obj)
        throw std::runtime_error("Cannot write " + objPath.string());
    obj << "# Generated by space\nmtllib " << mtlPath.filename().generic_string() << '\n';

    std::size_t base = 1; // OBJ indices are 1-based and shared across the file
    for (const ModelData::SubMesh& sub : model.subMeshes) {
        obj << "\nusemtl " << model.materials[sub.materialIndex].name << '\n';
        for (const Vertex& v : sub.mesh.vertices)
            obj << "v " << v.position.x << ' ' << v.position.y << ' ' << v.position.z << '\n';
        for (const Vertex& v : sub.mesh.vertices)
            obj << "vt " << v.texcoord.x << ' ' << v.texcoord.y << '\n';
        for (const Vertex& v : sub.mesh.vertices)
            obj << "vn " << v.normal.x << ' ' << v.normal.y << ' ' << v.normal.z << '\n';
        const auto& idx = sub.mesh.indices;
        for (std::size_t i = 0; i + 2 < idx.size(); i += 3) {
            obj << 'f';
            for (int k = 0; k < 3; ++k) {
                const std::size_t n = base + idx[i + k];
                obj << ' ' << n << '/' << n << '/' << n;
            }
            obj << '\n';
        }
        base += sub.mesh.vertices.size();
    }
}

} // namespace space
